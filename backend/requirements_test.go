package guardian_test

// Every requirement in docs/USERS.md that is done has at least one test naming it, and every id a test names
// is a requirement. A test names what it covers in its doc comment:
//
//	// Covers: V1, U3
//	func TestE2ESomething(t *testing.T) {
//
// The table of requirements and their tests in docs/TESTING.md is generated from the same data. When it is
// out of date this test fails; regenerate it with
//
//	UPDATE_REQUIREMENTS=1 go test -run TestEveryDoneRequirementHasATest .

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"testing"
)

const (
	usersDoc   = "../docs/USERS.md"
	testingDoc = "../docs/TESTING.md"
	tableStart = "<!-- requirements:start (generated by backend/requirements_test.go; do not edit by hand) -->"
	tableEnd   = "<!-- requirements:end -->"
)

type requirement struct {
	ID, Text, Release, Status string
}

func (r requirement) done() bool { return strings.HasPrefix(r.Status, "done") }

var (
	rowRe    = regexp.MustCompile(`^\| ([A-Z]+[0-9]+) \| (.+) \| ([^|]+) \| ([^|]+) \|$`)
	coversRe = regexp.MustCompile(`(?m)^Covers: (.+)$`)
	idRe     = regexp.MustCompile(`^[A-Z]+[0-9]+$`)
)

func requirements(t *testing.T) []requirement {
	t.Helper()
	b, err := os.ReadFile(usersDoc)
	if err != nil {
		t.Fatal(err)
	}
	var out []requirement
	seen := map[string]bool{}
	for _, line := range strings.Split(string(b), "\n") {
		m := rowRe.FindStringSubmatch(strings.TrimSpace(line))
		if m == nil || m[1] == "ID" {
			continue
		}
		if seen[m[1]] {
			t.Errorf("%s appears twice in USERS.md", m[1])
		}
		seen[m[1]] = true
		out = append(out, requirement{ID: m[1], Text: m[2], Release: strings.TrimSpace(m[3]), Status: strings.TrimSpace(m[4])})
	}
	if len(out) < 50 {
		t.Fatalf("found only %d requirements in %s: has the table's format changed?", len(out), usersDoc)
	}
	return out
}

// coverage maps each requirement id to the tests that name it, and reports ids that are not requirements.
func coverage(t *testing.T, known map[string]bool) map[string][]string {
	t.Helper()
	out := map[string][]string{}
	fset := token.NewFileSet()
	err := filepath.WalkDir(".", func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() && (d.Name() == "vendor" || strings.HasPrefix(d.Name(), ".")) && path != "." {
			return filepath.SkipDir
		}
		if d.IsDir() || !strings.HasSuffix(path, "_test.go") {
			return nil
		}
		f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			return err
		}
		for _, decl := range f.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Recv != nil || !strings.HasPrefix(fn.Name.Name, "Test") || fn.Doc == nil {
				continue
			}
			for _, m := range coversRe.FindAllStringSubmatch(fn.Doc.Text(), -1) {
				for _, id := range strings.Split(m[1], ",") {
					id = strings.TrimSpace(strings.TrimSuffix(strings.TrimSpace(id), "."))
					if !idRe.MatchString(id) || !known[id] {
						t.Errorf("%s (%s) covers %q, which is not a requirement in USERS.md", fn.Name.Name, path, id)
						continue
					}
					out[id] = append(out[id], fn.Name.Name)
				}
			}
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	for id := range out {
		sort.Strings(out[id])
	}
	return out
}

func table(reqs []requirement, cov map[string][]string) string {
	var b strings.Builder
	b.WriteString(tableStart + "\n\n| Id | Status | Tests |\n|---|---|---|\n")
	for _, r := range reqs {
		tests := "—"
		if names := cov[r.ID]; len(names) > 0 {
			tests = "`" + strings.Join(names, "`, `") + "`"
		}
		fmt.Fprintf(&b, "| %s | %s | %s |\n", r.ID, r.Status, tests)
	}
	b.WriteString("\n" + tableEnd)
	return b.String()
}

func TestEveryDoneRequirementHasATest(t *testing.T) {
	reqs := requirements(t)
	known := map[string]bool{}
	for _, r := range reqs {
		known[r.ID] = true
	}
	cov := coverage(t, known)
	for _, r := range reqs {
		if r.done() && len(cov[r.ID]) == 0 {
			t.Errorf("%s is done but no test covers it (add \"Covers: %s\" to a test's doc comment): %.90s", r.ID, r.ID, r.Text)
		}
	}

	doc, err := os.ReadFile(testingDoc)
	if err != nil {
		t.Fatal(err)
	}
	s := string(doc)
	start, end := strings.Index(s, tableStart), strings.Index(s, tableEnd)
	if start < 0 || end < start {
		t.Fatalf("%s lacks the generated table's markers", testingDoc)
	}
	want := table(reqs, cov)
	if got := s[start : end+len(tableEnd)]; got != want {
		if os.Getenv("UPDATE_REQUIREMENTS") == "1" {
			if err := os.WriteFile(testingDoc, []byte(s[:start]+want+s[end+len(tableEnd):]), 0o644); err != nil {
				t.Fatal(err)
			}
			t.Logf("updated the requirements table in %s", testingDoc)
			return
		}
		t.Errorf("the requirements table in %s is out of date: run UPDATE_REQUIREMENTS=1 go test -run TestEveryDoneRequirementHasATest .", testingDoc)
	}
}
